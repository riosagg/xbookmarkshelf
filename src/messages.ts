export type Language = 'ja' | 'en';
export type LanguagePreference = Language | 'system';
export type MessageKey = keyof typeof english;
export type Parameters = Readonly<Record<string, string | number>>;
export type UIMessage = string | { key: MessageKey; params: Parameters };
export function isLanguage(value: unknown): value is Language { return value === 'ja' || value === 'en'; }
export function isLanguagePreference(value: unknown): value is LanguagePreference { return value === 'system' || isLanguage(value); }
export function resolveLanguage(preference: LanguagePreference, browserLocale: string): Language {
  return isLanguage(preference) ? preference : /^ja(?:[-_]|$)/i.test(browserLocale) ? 'ja' : 'en';
}
export function browserUILanguage(): string {
  try {
    const locale = typeof chrome !== 'undefined' ? chrome.i18n?.getUILanguage?.() : undefined;
    if (locale) return locale;
  } catch { /* Fall back outside extension pages or when the browser API is unavailable. */ }
  return typeof navigator !== 'undefined' ? navigator.language : 'en';
}
export function translate(language: Language, key: MessageKey, params: Parameters = {}): string {
  const template = language === 'en' ? english[key] : key;
  return template.replace(/\{(\w+)\}/g, (placeholder, name: string) => Object.hasOwn(params, name) ? String(params[name]) : placeholder);
}
export function translateUIMessage(language: Language, value: UIMessage): string {
  if (typeof value !== 'string') return translate(language, value.key, value.params);
  if (!value) return '';
  if (Object.hasOwn(english, value)) return translate(language, value as MessageKey);
  return language === 'ja' ? value : english['処理に失敗しました'];
}
export function dateLocale(language: Language): string { return language === 'en' ? 'en-US' : 'ja-JP'; }
